-- VIEW (PERSONA_SCI)

CREATE OR REPLACE FORCE EDITIONABLE VIEW "BDSCI"."PERSONA_SCI" ("RUN", "GRADO", "NOMBRES", "APELLIDO_PATERNO", "APELLIDO_MATERNO", "FONO", "CORREOINTER") AS 
SELECT  RUN,
        TRANSLATE(GRADO USING NCHAR_CS) AS GRADO,
        TRANSLATE(NOMBRES USING NCHAR_CS) AS NOMBRES,
        TRANSLATE(APELLIDO_PATERNO USING NCHAR_CS) AS APELLIDO_PATERNO,
        TRANSLATE(APELLIDO_MATERNO USING NCHAR_CS) AS APELLIDO_MATERNO,
        TRANSLATE(FONO USING NCHAR_CS) AS FONO,
        TRANSLATE(CORREOINTER USING NCHAR_CS) AS CORREOINTER
FROM    PERSONA
UNION
SELECT  RUN,
        TRANSLATE(GRADO USING NCHAR_CS) AS GRADO,
        TRANSLATE(NOMBRES USING NCHAR_CS) AS NOMBRES,
        TRANSLATE(APELLIDO_PATERNO USING NCHAR_CS) AS APELLIDO_PATERNO,
        TRANSLATE(APELLIDO_MATERNO USING NCHAR_CS) AS APELLIDO_MATERNO,
        TRANSLATE(FONO USING NCHAR_CS) AS FONO,
        TRANSLATE(CORREOINTER USING NCHAR_CS) AS CORREOINTER
FROM    PERSONAS_CIVILES
ORDER BY RUN ASC WITH READ ONLY;
COMMENT ON TABLE "BDSCI"."PERSONA_SCI"  IS 'VIEW para unificar información de la Tabla PERSONA y PERSONAS_CIVILES del sistema SCI para busquedas.';


